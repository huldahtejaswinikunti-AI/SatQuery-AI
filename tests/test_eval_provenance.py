"""
Provenance and rigor test for evaluation results.

Validates that every result artifact in `evaluation/results/*.json` contains a
standard `provenance` block generated during an actual execution run, and that
the sample size meets or exceeds the minimum statistical floor (n >= 30).
"""

from __future__ import annotations

import json
from pathlib import Path
import pytest


RESULTS_DIR = Path(__file__).resolve().parent.parent / "evaluation" / "results"
MIN_SAMPLE_FLOOR = 30


def get_evaluation_json_files() -> list[Path]:
    """Retrieve all JSON evaluation result files."""
    if not RESULTS_DIR.is_dir():
        return []
    return sorted(list(RESULTS_DIR.glob("*.json")))


def test_results_directory_not_empty():
    """Ensure evaluation results exist."""
    files = get_evaluation_json_files()
    assert len(files) > 0, f"No JSON result files found in {RESULTS_DIR}"


@pytest.mark.parametrize(
    "json_file",
    get_evaluation_json_files(),
    ids=lambda p: p.name,
)
def test_evaluation_file_provenance_and_rigor(json_file: Path):
    """Assert provenance block, valid git commit, and sample size floor."""
    with open(json_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    # 1. Provenance block presence
    assert "provenance" in data, (
        f"Evaluation result {json_file.name} lacks a 'provenance' block. "
        "Every artifact in evaluation/results must be generated by a script with provenance."
    )

    prov = data["provenance"]
    assert isinstance(prov, dict), f"'provenance' in {json_file.name} must be a dictionary."

    # 2. Required provenance metadata fields
    for field in ("script", "timestamp", "git_commit", "total_samples"):
        assert field in prov, f"Missing required provenance field '{field}' in {json_file.name}."

    # 3. Valid git commit hash
    git_commit = str(prov["git_commit"]).strip()
    assert len(git_commit) >= 7, (
        f"Git commit hash '{git_commit}' in {json_file.name} is too short or invalid."
    )

    # 4. Total samples floor check (>= 30)
    total_samples = int(prov["total_samples"])
    assert total_samples >= MIN_SAMPLE_FLOOR, (
        f"Evaluation {json_file.name} has total_samples={total_samples}, "
        f"which is below the minimum statistical floor of {MIN_SAMPLE_FLOOR}."
    )

    # 5. Top-level total_samples consistency if present
    if "total_samples" in data:
        assert int(data["total_samples"]) >= MIN_SAMPLE_FLOOR
